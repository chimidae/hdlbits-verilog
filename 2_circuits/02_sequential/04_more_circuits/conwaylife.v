// 헷갈린 부분:
// 논리보다 인덱스 계산이 전부인 문제다. 256비트를 16x16 격자로
// 보고, j번 셀의 행은 j/16, 열은 j%16이다.
//
// 토로이드 경계는 조건 분기 없이 & 15 마스킹으로 접힌다.
// (j%16 - 1) & 15는 0에서 15로, (j%16 + 1) & 15는 15에서 0으로
// 자동으로 감싸진다.
//
// 1차 시도에서 (j/16)*16 + (j%16 - 1) & 15로 써서 실패했다.
// &가 +보다 우선순위가 낮아 덧셈 전체에 & 15가 걸려버린다.
// 랩어라운드시킬 항만 괄호로 묶어야 한다.
//     (j/16)*16 + ((j%16 - 1) & 15)
//
// 이웃 8개의 합으로 판정한다. 2면 유지, 3이면 생존, 나머지는 사망.
//==============================================================

module top_module(
    input clk,
    input load,
    input [255:0] data,
    output [255:0] q );
    integer j;
    always @(posedge clk) begin
        if (load) begin //일단 로드를 빼.
            q <= data; 
        end
        else begin
            for (j=0; j<256; j=j+1) begin
                case (q[(j/16)*16 + ((j%16 - 1) & 15)] + q[(j/16)*16 + ((j%16 + 1) & 15)] //같은 열
                      + q[((j/16 - 1) & 15)*16 + ((j%16 - 1) & 15)] + q[((j/16 - 1) & 15)*16 + j%16] + q[((j/16 - 1) & 15)*16 + ((j%16 + 1) & 15)]
                      + q[((j/16 + 1) & 15)*16 + ((j%16 - 1) & 15)] + q[((j/16 + 1) & 15)*16 + j%16] + q[((j/16 + 1) & 15)*16 + ((j%16 + 1) & 15)])
                    4'b0010 : q[j] <= q[j];
                    4'b0011 : q[j] <= 1;
                    default : q[j] <= 0;
                endcase
            end
        end
    end
endmodule
